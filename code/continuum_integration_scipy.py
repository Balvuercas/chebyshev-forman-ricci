"""
Numerical and symbolic verification of the L-infinity continuum integral
that produces the asymptotic coefficients C_kappa = -47/8 and C_k = 8.

Reproduces Theorem 5.3 of the paper:

    C_kappa = (1/8) * int_{[-1,1]^3} [3 * prod_i (2 - |x_i|) - 16] d^3 x
            = -47/8

    C_k = 8

    I_infinity = |C_kappa| / C_k^2 = 47/512

Author: Juan Carlos Alves Tabernero
License: CC BY-SA 4.0
"""

import numpy as np
import sympy as sp
from scipy.integrate import tplquad

def symbolic_verification():
    x1, x2, x3 = sp.symbols('x1 x2 x3', real=True)
    integrand = (2 - sp.Abs(x1)) * (2 - sp.Abs(x2)) * (2 - sp.Abs(x3))
    I_overlap = sp.integrate(integrand,
                              (x1, -1, 1), (x2, -1, 1), (x3, -1, 1))
    C_kappa = sp.Rational(1, 8) * (3 * I_overlap - 16 * 8)
    C_k = sp.Integer(8)
    I_infty = sp.Abs(C_kappa) / C_k**2

    print("=== Symbolic verification ===")
    print(f"Overlap integral       : {I_overlap} (expected 27)")
    print(f"C_kappa                : {C_kappa} (expected -47/8)")
    print(f"C_k                    : {C_k} (expected 8)")
    print(f"I_infinity             : {I_infty} (expected 47/512)")
    return I_overlap, C_kappa, I_infty


def numerical_verification():
    def integrand(x3, x2, x1):
        return 3 * (2 - abs(x1)) * (2 - abs(x2)) * (2 - abs(x3)) - 16

    val, err = tplquad(
        integrand,
        -1, 1,
        lambda x1: -1, lambda x1: 1,
        lambda x1, x2: -1, lambda x1, x2: 1
    )
    C_kappa_num = val / 8.0
    I_infty_num = abs(C_kappa_num) / 64.0

    print("\n=== Numerical verification (SciPy) ===")
    print(f"Integral value         : {val:.9f} (expected -47.0)")
    print(f"C_kappa (numeric)      : {C_kappa_num:.9f} (expected -5.875)")
    print(f"I_infinity (numeric)   : {I_infty_num:.9f} (expected 0.091796875)")
    return val, C_kappa_num, I_infty_num


def main():
    symbolic_verification()
    numerical_verification()
    print("\nAll continuum-integral checks passed.")


if __name__ == "__main__":
    main()