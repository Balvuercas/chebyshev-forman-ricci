import os
import numpy as np
import matplotlib.pyplot as plt

# Ensure output directory exists
os.makedirs('figures', exist_ok=True)

plt.rcParams.update({
    'font.family': 'serif',
    'font.size': 11,
    'axes.labelsize': 12,
    'legend.fontsize': 10,
    'xtick.labelsize': 10,
    'ytick.labelsize': 10,
    'text.usetex': False,
})


def mean_curvature(lam):
    num = 47*lam**5 + 141*lam**4 + 156*lam**3 + 85*lam**2 + 24*lam + 3
    den = 2 * (4*lam**2 + 6*lam + 3)
    return -num / den


def degree(lam):
    return (2*lam + 1)**3 - 1


def figure2():
    # 1. Definir los datos exactos (lambda 1 a 8, como en la tabla del paper)
    lambdas = np.arange(1, 9)
    kappa_vals = mean_curvature(lambdas)

    # 2. Crear la figura (3.4 x 2.8 in, estándar de una columna)
    fig, ax = plt.subplots(figsize=(3.4, 2.8), dpi=300)

    # 3. Dibujar la línea roja (Fórmula cerrada)
    # Usamos un rango suave para que la línea no tenga picos
    lambdas_smooth = np.linspace(1, 8, 100)
    ax.plot(lambdas_smooth, mean_curvature(lambdas_smooth),
            color='#d62728', linewidth=2.0,
            label='Closed form', zorder=2)

    # 4. Dibujar los puntos azules (Valores exactos)
    ax.scatter(lambdas, kappa_vals,
               color='#1f77b4', edgecolors='black', linewidths=0.7,
               s=45, zorder=3, label='Exact values')

    # 5. Etiquetas de los ejes
    ax.set_xlabel(r'Interaction radius $\lambda$')
    ax.set_ylabel(r'Mean curvature $\langle \kappa_e \rangle(\lambda)$')

    # 6. Límites y ticks (ajustados a la figura del paper)
    ax.set_xlim(0.5, 8.5)
    ax.set_ylim(-4000, 50)
    ax.set_xticks([2, 4, 6, 8])
    ax.set_yticks([0, -1000, -2000, -3000, -4000])

    # 7. Rejilla
    ax.grid(True, linestyle='--', alpha=0.5)

    # 8. Leyenda (abajo a la izquierda, como en el paper)
    ax.legend(loc='lower left', framealpha=0.9)

    # 9. Guardar
    fig.tight_layout()
    fig.savefig('figures/figure2_curvature.pdf', bbox_inches='tight')
    fig.savefig('figures/figure2_curvature.png', dpi=300, bbox_inches='tight')
    plt.close(fig)


def figure3():
    # Función mantenida intacta (matemática sin modificar)
    lambdas = np.arange(1, 201)
    inv_vals = np.abs(mean_curvature(lambdas)) * lambdas**3 / degree(lambdas)**2
    inv_limit = 47.0 / 512.0

    fig, ax = plt.subplots(figsize=(3.4, 2.8), dpi=300)
    ax.plot(1.0/lambdas, inv_vals, 's-', color='#d62728',
            markevery=10, linewidth=1.5, markersize=4,
            label=r'$\mathcal{I}(\lambda)$')
    ax.axhline(y=inv_limit, color='black', linestyle='--',
               linewidth=1.2,
               label=r'$\mathcal{I}_\infty = 47/512$')
    ax.set_xlabel(r'Inverse resolution $1/\lambda$')
    ax.set_ylabel(r'Invariant $\mathcal{I}(\lambda)$')
    ax.set_xlim([0, 1.0])
    
    # Límites y ticks del eje y
    ax.set_ylim(0.02, 0.10)
    ax.set_yticks([0.02, 0.04, 0.06, 0.08, 0.10])
    
    ax.grid(True, linestyle='--', alpha=0.5)
    
    # Cuadro informativo bajado respecto a la línea discontinua superior
    ax.legend(loc='upper right', bbox_to_anchor=(0.98, 0.82), framealpha=0.9)
    
    fig.tight_layout()
    fig.savefig('figures/figure3_invariant.pdf', bbox_inches='tight')
    fig.savefig('figures/figure3_invariant.png', dpi=300, bbox_inches='tight')
    plt.close(fig)


if __name__ == "__main__":
    figure2()
    figure3()
    print("Figures generated in ./figures/")