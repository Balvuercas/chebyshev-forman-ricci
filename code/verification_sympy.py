"""
Symbolic verification of the closed-form mean curvature formula
for Forman-Ricci curvature on the 3D Chebyshev toroidal lattice.

Reproduces the algebraic identity proved in Appendix A of the paper:

    <kappa_e>(lambda) = -N(lambda) / [2(4 lambda^2 + 6 lambda + 3)]

with N(lambda) = 47 lambda^5 + 141 lambda^4 + 156 lambda^3
                + 85 lambda^2 + 24 lambda + 3.

Author: Juan Carlos Alves Tabernero
License: CC BY-SA 4.0
"""

import sympy as sp

def main():
    lam = sp.symbols('lam', positive=True, integer=True)

    # Basic building blocks
    k = (2*lam + 1)**3 - 1
    T = (3*lam**2 + 3*lam + 1)**3 - (2*lam + 1)**3
    S = T - 2*k

    # Discrete mean curvature from the triangle sum
    kappa_exact = -2 - 2*k + (3*T)/k

    # Closed-form expression
    numerator = 47*lam**5 + 141*lam**4 + 156*lam**3 + 85*lam**2 + 24*lam + 3
    denominator = 2*(4*lam**2 + 6*lam + 3)
    kappa_closed = -numerator / denominator

    # Verification
    diff = sp.simplify(kappa_exact - kappa_closed)
    print(f"Algebraic difference (exact - closed): {diff}")

    # Also check S(lambda) explicitly
    S_expected = (3*lam**2 + 3*lam + 1)**3 - 3*(2*lam + 1)**3 + 2
    diff_S = sp.simplify(S - S_expected)
    print(f"Triangle sum difference: {diff_S}")

    # Numerical spot-check for lambda = 1..8
    print("\nNumerical spot-check:")
    for n in range(1, 9):
        val = float(kappa_closed.subs(lam, n))
        print(f"  lambda={n}: <kappa_e> = {val:.6f}")

    assert diff == 0, "Closed-form formula does not match exact expression"
    assert diff_S == 0, "Triangle sum formula is incorrect"
    print("\nAll symbolic checks passed.")


if __name__ == "__main__":
    main()