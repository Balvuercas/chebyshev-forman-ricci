"""
Brute-force verification of the closed-form mean curvature for lambda = 3.

Builds the Chebyshev toroidal graph explicitly for L = 4*lambda = 12
and computes the mean Forman-Ricci curvature directly from the
definition, then compares with the closed-form formula.

Author: Juan Carlos Alves Tabernero
License: CC BY-SA 4.0
"""

import os
import time
import numpy as np
import networkx as nx

os.makedirs('data', exist_ok=True)


def chebyshev_distance_on_torus(p, q, L):
    """Chebyshev (L-infinity) distance on the torus of side L."""
    dx = min(abs(p[0] - q[0]), L - abs(p[0] - q[0]))
    dy = min(abs(p[1] - q[1]), L - abs(p[1] - q[1]))
    dz = min(abs(p[2] - q[2]), L - abs(p[2] - q[2]))
    return max(dx, dy, dz)


def build_chebyshev_graph(L, lam):
    """Build the Chebyshev toroidal graph using the offset-list method."""
    from itertools import product

    coords = list(product(range(L), repeat=3))
    idx = {c: i for i, c in enumerate(coords)}
    G = nx.Graph()
    G.add_nodes_from(range(len(coords)))

    # Build the neighbour offset list once
    offsets = []
    for dx in range(-lam, lam + 1):
        for dy in range(-lam, lam + 1):
            for dz in range(-lam, lam + 1):
                if (dx, dy, dz) == (0, 0, 0):
                    continue
                if max(abs(dx), abs(dy), abs(dz)) > lam:
                    continue
                offsets.append((dx, dy, dz))

    for c in coords:
        i = idx[c]
        for dx, dy, dz in offsets:
            n = ((c[0] + dx) % L, (c[1] + dy) % L, (c[2] + dz) % L)
            j = idx[n]
            if i < j:
                G.add_edge(i, j)
    return G


def forman_curvature_of_edge(G, u, v):
    """Forman-Ricci curvature of a single edge."""
    deg_u = G.degree(u)
    deg_v = G.degree(v)
    common = len(set(G.neighbors(u)) & set(G.neighbors(v)))
    return 4 - deg_u - deg_v + 3 * common


def mean_forman_curvature(G):
    """Mean Forman-Ricci curvature over all edges."""
    total = 0.0
    for u, v in G.edges():
        total += forman_curvature_of_edge(G, u, v)
    return total / G.number_of_edges()


def closed_form(lam):
    """Closed-form mean curvature."""
    num = 47*lam**5 + 141*lam**4 + 156*lam**3 + 85*lam**2 + 24*lam + 3
    den = 2 * (4*lam**2 + 6*lam + 3)
    return -num / den


def main():
    lam = 3
    L = 4 * lam
    print(f"Building Chebyshev graph for lambda = {lam}, L = {L}...")
    t0 = time.time()
    G = build_chebyshev_graph(L, lam)
    print(f"  Nodes: {G.number_of_nodes()}")
    print(f"  Edges: {G.number_of_edges()}")
    print(f"  Build time: {time.time() - t0:.2f} s")

    # Verify degree
    degrees = [d for _, d in G.degree()]
    mean_deg = np.mean(degrees)
    expected_deg = (2*lam + 1)**3 - 1
    print(f"\n  Mean degree (numerical) : {mean_deg:.4f}")
    print(f"  Expected degree         : {expected_deg}")
    assert abs(mean_deg - expected_deg) < 1e-6, "Degree mismatch"

    # Mean curvature (brute force)
    print(f"\nComputing mean curvature (this may take a moment)...")
    t0 = time.time()
    kappa_num = mean_forman_curvature(G)
    print(f"  Numerical mean curvature: {kappa_num:.10f}")
    print(f"  Time: {time.time() - t0:.2f} s")

    # Closed-form
    kappa_cf = closed_form(lam)
    print(f"\n  Closed-form curvature   : {kappa_cf:.10f}")
    print(f"  Absolute difference     : {abs(kappa_num - kappa_cf):.2e}")
    print(f"  Relative difference     : {abs(kappa_num - kappa_cf)/abs(kappa_cf):.2e}")

    # Write result to file
    with open('data/brute_force_lambda3.txt', 'w') as f:
        f.write(f"lambda = {lam}, L = {L}\n")
        f.write(f"Nodes: {G.number_of_nodes()}, Edges: {G.number_of_edges()}\n")
        f.write(f"Mean degree (numerical): {mean_deg:.10f}\n")
        f.write(f"Mean degree (expected) : {expected_deg}\n")
        f.write(f"Numerical mean curvature: {kappa_num:.15f}\n")
        f.write(f"Closed-form curvature   : {kappa_cf:.15f}\n")
        f.write(f"Absolute difference     : {abs(kappa_num - kappa_cf):.2e}\n")
        f.write(f"Relative difference     : {abs(kappa_num - kappa_cf)/abs(kappa_cf):.2e}\n")
    print(f"\nResult saved to data/brute_force_lambda3.txt")


if __name__ == "__main__":
    main()